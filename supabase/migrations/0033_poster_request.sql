-- בקשת חברות היא חצי פנייה, לא פנייה.
--
-- 13.11.2026. שאול הסתכל על הכרטיס של דיקלה לסרי ושאל: "בקשת חברות אני
-- אמור לסמן נשלח?"
--
-- לא. הסדר האמיתי הוא שלושה צעדים: בקשה, אישור שלה, ואז ההודעה עם הקובץ.
-- סימון "נשלח" על הבקשה היה מוריד את השורה מהתור, ושום דבר לא היה מחזיר
-- אותה כשהיא מאשרת. החצי השני פשוט לא היה קורה, ובלי שום סימן.
--
-- לכן שני שדות ולא אחד: poster_request_at הוא הפתק שיצא בבקשת החברות,
-- ו-poster_sent_at נשאר ההודעה עם הקובץ. למי ששאול כבר מחובר אליו יש רק
-- את השני, וזה בדיוק ההבדל בין שני המסלולים.

alter table jobs add column if not exists poster_request_at timestamptz;

