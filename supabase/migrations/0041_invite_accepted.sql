-- מי שאישר בקשת חברות בלינקדאין.
--
-- ‏15.11.2026. שאול שלח צילום של מייל "Ron accepted your invitation" וביקש:
-- "מי שמאשר או מאשרת חברות, לשלוח לה או לו מכתב להגשת קורות חיים כמו שאני
-- שולח לכולם. זה צריך להיות מתויג אישר חברות והמכתב צריך להיות יותר אישי
-- עם התעניינות למקרה שיש להם משרות פתוחות".
--
-- **זאת החוליה שהייתה חסרה בתור "ממתין לאישור".** ב-13.11 נקבע ששליחת
-- בקשת חברות אינה פנייה אלא חצי פנייה, ושיש שלושה צעדים: בקשה, אישור, ואז
-- ההודעה עם הקובץ. הצעד האמצעי היה היחיד שאף אחד לא ידע עליו: שאול היה
-- צריך לשים לב בעצמו שמישהו אישר.
--
-- **והאישור מגיע במייל.** `invitations@linkedin.com`, והשם המלא יושב בשם
-- התצוגה, "Ron Dvash via LinkedIn". נמדד: חמישה אישורים בארבעה עשר יום.
-- אין כאן שום גריפה, זה מייל שנשלח אליו.
--
-- **ולמה זה לא סותר את "מגייסים צד שלישי לא נשמרים".** הכלל מבחין בין קשר
-- מדרגה ראשונה לבין מי שאינו. אדם שאישר את בקשת החברות שלו **הוא** קשר
-- מדרגה ראשונה, מרגע האישור. זה לא חריג לכלל אלא בדיוק הצד המותר שלו.
--
-- `invite_accepted_at` הוא גם התיוג שהוא ביקש וגם התור: מי שאישר ועוד לא
-- נשלח אליו `contacted_at` הוא מי שממתין למכתב.

alter table contacts add column if not exists invite_accepted_at timestamptz;

-- מאיפה הגיע איש הקשר. ההבחנה חשובה כי מי שהגיע מאישור בקשה אינו מהייצוא
-- של אנשי הקשר, ולכן אין לו company_key ולרוב גם לא חברה.
alter table contacts add column if not exists source text;

create index if not exists contacts_invite_accepted_idx
    on contacts (invite_accepted_at desc)
    where invite_accepted_at is not null and contacted_at is null;

notify pgrst, 'reload schema';
