-- משרות שהגיעו מהחיפוש הבוליאני בגוגל, ולא מלוח.
--
-- 14.11.2026. שאול שלח את המדריך "מתחת לרדאר" של ניסן איטל וביקש להתאים
-- אותו לחיפושים שלו, בטאב נפרד. לב המדריך הוא שאילתת site: אחת שסורקת את
-- כל פלטפורמות ה-ATS בבת אחת במקום לקרוא לוח אחד אחד.
--
-- **ההבדל מהסריקה הרגילה, וזה מה שמצדיק עמודה.** הסורקים שלנו קוראים 27
-- לוחות Greenhouse לפי רשימת שמות קבועה, ולכן הם מוצאים רק מה שבחברות
-- שאנחנו כבר מכירים. באותו ערב שאול שלח משרה ב-Alteva RCM ושאל למה לא
-- מצאנו אותה, והתשובה הייתה שהחברה לא הייתה ברשימה. חיפוש בגוגל אינו מוגבל
-- לרשימה, ולכן הוא מביא סוג אחר של תוצאה וראוי למסך משלו.
--
-- **ולמה בלי שער גיל.** בלוח ATS מודעה שנסגרה נעלמת, ולכן מה שמופיע שם
-- פתוח בהגדרה. שאול שמע את זה בהדרכה באותו ערב וצדק: "הם ממליצים לעשות
-- חיפוש גם שנה אחורה, ואם הן מופיעות בדף החברה הן עדיין קיימות". לכן
-- המסך מציג הכל, ושורה יורדת רק כשהוא סוגר אותה: "אתה לא מוחק גם אם עברו
-- כמה ימים, רק אני סוגר".
--
-- `dismissed_at` הקיים הוא הסגירה, ואין צורך במנגנון שני.

alter table jobs add column if not exists seo boolean not null default false;

-- המסך שולף לפי הדגל ולפי תאריך, ובלי האינדקס זאת סריקה מלאה בכל טעינה.
create index if not exists jobs_seo_idx
    on jobs (first_seen desc)
    where seo and dismissed_at is null;

