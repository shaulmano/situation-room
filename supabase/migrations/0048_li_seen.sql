-- מי שכבר יש איתו שיחה בלינקדאין.
--
-- 15.11.2026. שאול עצר את הפנייה הרחבה אחרי יותר מעשר שליחות: "כולן
-- כבר קיבלו ממני לפני כמה חודשים את ההודעה הראשונה שרק התחלנו בחיפוש.
-- זה נראה לי סתם שליחה כי גם אז לא ענו לי."
--
-- **המערכת ידעה על 97 בלבד מתוך 2,662.** היא נבנתה אחרי הגל הראשון
-- שלו, ולכן כל מי שכתב לו לפני כן לא היה מסומן, והתור שלח אותו שוב.
--
-- **האמת יושבת ברשימת השיחות בלינקדאין**: שיחה קיימת פירושה שכבר כתב.
-- הסוכן שקורא את התיבה טוען את כל הרשימה בכל ריצה ממילא, וזרק את כל
-- מי שלא ממתין לתשובה.
--
-- **נפרד מ-`contacted_at` בכוונה.** שם זה "פניתי אליו על משרה", וזה
-- המכנה של אחוז המענה. ערבוב היה מזייף אותו.
alter table contacts add column if not exists li_seen_at timestamptz;

create index if not exists contacts_li_seen_idx on contacts (li_seen_at)
  where li_seen_at is not null;

