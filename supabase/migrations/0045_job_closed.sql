-- משרה שנסגרה: המודעה עצמה כבר לא קיימת.
--
-- 15.11.2026, שאול: "אני רוצה גם אופציה לסמן מישרה שנסגרה", ובשאלה
-- מה הכוונה: "המודעה כבר לא קיימת".
--
-- **זה לא `dismissed_at`.** ✕ הוא החלטה שלו, "לא רלוונטית אלי". סגירה
-- היא עובדה על העולם: הלוח הוריד את המודעה. שתי העובדות נפרדות, ושתיהן
-- מורידות את השורה מהמסך, אבל רק אחת מהן אומרת משהו על המשרה עצמה.
--
-- ולמה זה שווה עמודה: הזיהוי במערכת הוא לפי כתובת, ואותה מודעה בשני
-- לוחות היא שתי שורות. סגירה חייבת לסגור את שתיהן, ובלי לדעת **למה**
-- שורה נסגרה אי אפשר להבדיל בין "הוא לא רצה" לבין "המודעה מתה".
--
-- `seo_jobs.py` כבר מגלה את זה לבד ברדאר, דרך `posting_is_live`, וכותב
-- עד היום רק `dismissed_at`. מעכשיו הוא כותב גם כאן, ולכן שתי הדרכים,
-- הידנית והאוטומטית, מסמנות את אותו דבר באותו מקום.
alter table jobs add column if not exists closed_at timestamptz;

create index if not exists jobs_closed_at_idx on jobs (closed_at)
  where closed_at is not null;

-- המלכודת שחזרה כאן כבר פעמיים: בלי זה PostgREST ממשיך להחזיר
-- "column does not exist", והמסכים מציגים אפס שורות **בלי שגיאה**.
notify pgrst, 'reload schema';
