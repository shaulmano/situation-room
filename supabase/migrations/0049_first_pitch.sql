-- גל הפניות של מאי 2026: מי שכבר קיבל את ההודעה הראשונה.
--
-- 15.11.2026. שאול עצר את הפנייה הרחבה באמצע: "אחרי שליחה של יותר מ-10
-- אני רואה שכולן כבר קיבלו ממני לפני כמה חודשים את ההודעה הראשונה שרק
-- התחלנו בחיפוש. זה נראה לי סתם שליחה כי גם אז לא ענו לי."
--
-- הוא צדק, והמסד לא ידע את זה. הראיה יושבת בתיקיית `job-search` במחשב
-- שלו, ב-`outreach_done.txt`: 1,214 שורות מהגל של מאי, ומתוכן
-- **920 "Connect sent"** ועוד 11 "Message sent".
--
-- **ובקשת חברות היא פנייה, כי היא נשאה נוסח.** `linkedin_connect.py`
-- שלח עם כל בקשה הערה: "I'm Shaul — actively looking for my next role as
-- a Senior Program Manager / QA Leader. Happy to send my CV if anything
-- fits." זאת בדיוק ההודעה הראשונה שהוא מדבר עליה, ולכן מי שקיבל בקשה
-- נחשב כמי שקיבל פנייה, גם אם מעולם לא נפתח שרשור.
--
-- **ולמה עמודה חדשה ולא `li_seen_at`.** זה היה נוח, ו-`eligible` כבר
-- פוסל אותה, אבל `li_seen_at` אומר "קיימת שיחה בלינקדאין", ולמי שלא
-- אישר את הבקשה אין שום שיחה. עמודה שאומרת דבר אחד ומשמשת לדבר אחר היא
-- בדיוק סוג השקר השקט שהפיל כאן דברים לאורך כל 2026.
--
-- **הנתון נשמר ולא נמחק.** אם שאול יחליט בעוד חצי שנה שפנייה שנייה למי
-- שלא ענה היא בכל זאת שווה, התאריך כאן הוא מה שיאפשר להחליט לפי מידה
-- ולא לפי זיכרון.
alter table contacts add column if not exists first_pitch_at timestamptz;

-- התור נשלף לפי "עוד לא נשלח ולא ויתרתי", והפסילה הזאת נבדקת על כל שורה.
create index if not exists contacts_first_pitch_idx on contacts (first_pitch_at)
  where first_pitch_at is not null;

-- המלכודת שחזרה כאן כבר פעמיים: בלי זה PostgREST ממשיך להחזיר
-- "column does not exist", והמסכים מציגים אפס שורות בלי שגיאה.
notify pgrst, 'reload schema';
